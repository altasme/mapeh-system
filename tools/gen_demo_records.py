#!/usr/bin/env python3
"""Generate supabase/seed/demo_records.sql: the legacy seedDemoData() shape with a fixed seed.
11 districts x 3 terms x 4 grades x 11 subjects = 1,452 rows, every row is_demo = true.
Run:  python3 tools/gen_demo_records.py > supabase/seed/demo_records.sql
"""
import json, random, re
random.seed(20251001)
DISTRICTS = ["Asuncion","B.E. Dujali","Carmen","Kapalong East","Kapalong West","New Corella",
             "San Isidro","Sto. Tomas East","Sto. Tomas West","Talaingod","Langilan"]
GRADES = [("Grade 1","Key Stage 1"),("Grade 4","Key Stage 2"),("Grade 8","Key Stage 3"),("Grade 11","Key Stage 4")]
SUBJECTS = ["MAPEH - Music & Arts","MAPEH - PE & Health","SPA - Vocal Arts","SPA - Dance Arts",
            "SPS - Basketball","SPS - Volleyball","SPFL - Spanish","SPFL - Japanese (Nihongo)",
            "IPED - English","IPED - Mathematics","IPED - MAPEH (Music & Arts)"]
def pl(m): return "Advanced" if m>=90 else "Proficient" if m>=85 else "Approaching Proficiency" if m>=80 else "Developing" if m>=75 else "Beginning"
def q(s): return "'" + s.replace("'", "''") + "'"
rows = []
for dist in DISTRICTS:
    for term in ("Term 1","Term 2","Term 3"):
        for g, ks in GRADES:
            for sub in SUBJECTS:
                mps = round(65 + random.random()*25, 2)
                base = round(60 + random.random()*25, 2)
                p75 = round(min(98, mps + random.random()*6), 2)
                code = re.sub(r'[^a-zA-Z0-9]', '', sub)[:4].upper()
                gc = g.replace(' ', '', 1)
                school = ""
                if sub.startswith("SPA"): school = f"{dist} National High School (SPA Campus)"
                elif sub.startswith("SPS"): school = f"{dist} National High School (SPS Track)"
                elif sub.startswith("SPFL"): school = f"{dist} Regional Science High School"
                elif sub.startswith("IPED"): school = f"{dist} IPED Central Elementary School"
                ll = [{"code": f"{code}-{gc}-LC{i}", "desc": d % sub} for i, d in enumerate([
                    "Core performance and foundational skill mastery in %s",
                    "Tactical execution, contextualization, and grammar in %s",
                    "Indigenous cultural integration, vocabulary, and practical application in %s"], 1)]
                rows.append(f"((select id from public.districts where name={q(dist)}),'2025-2026',{q(term)},{q(school)},"
                            f"{q(ks)},{q(g)},{q(sub)},{base},{mps},{p75},{q(pl(mps))},{q(json.dumps(ll))}::jsonb,true,(select id from public.profiles where username='admin'))")
print("-- demo_records.sql: GENERATED by tools/gen_demo_records.py (fixed seed). Every row is_demo = true.")
print("-- Run AFTER districts.sql and after the admin profile exists (created_by needs it).")
print("-- Purge: delete from public.assessment_records where is_demo;")
for i in range(0, len(rows), 250):
    print("insert into public.assessment_records (district_id,sy,term,school,key_stage,grade_level,learning_area,baseline_mps,mps,pct75,proficiency_level,least_learned,is_demo,created_by) values")
    print(",\n".join(rows[i:i+250]) + ";")
