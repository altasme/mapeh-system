#!/usr/bin/env python3
"""Validate List-of-School.xlsx and produce (a) an idempotent SQL import and (b) a discrepancy report.
Usage: python3 -I tools/school_import.py <List-of-School.xlsx> <out_dir>
Reads: worksheet 'Secondary' (Secondary schools) and 'Sheet2' (Elementary schools).
Nothing here touches a database; the SQL is reviewed and run by a person in the Supabase SQL editor."""
import sys, json, re, collections, openpyxl

DISTRICT_ALIASES = {  # only mappings that are unambiguous
    'kap. east': 'Kapalong East', 'kap. west': 'Kapalong West', 'be. dujali': 'B.E. Dujali',
    'b.e. dujali': 'B.E. Dujali', 'san isidro': 'San Isidro', 'asuncion': 'Asuncion', 'carmen': 'Carmen',
    'langilan': 'Langilan', 'new corella': 'New Corella', 'sto. tomas east': 'Sto. Tomas East',
    'sto. tomas west': 'Sto. Tomas West', 'talaingod': 'Talaingod', 'kapalong east': 'Kapalong East', 'kapalong west': 'Kapalong West'}
SHEETS = [('Secondary', 'secondary'), ('Sheet2', 'elementary')]

def load(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    rows, issues = [], []
    for sheet, level in SHEETS:
        ws = wb[sheet]
        for n, r in enumerate(ws.iter_rows(values_only=True), 1):
            sid, no, name, dist = (list(r) + [None] * 4)[:4]
            if sid in (None, 'ID') and not name: continue
            if isinstance(sid, str) and not isinstance(sid, int):
                continue  # header-like lines (Region, Division, Congressional District)
            if sid is None:
                if isinstance(name, str) and name.strip():
                    issues.append({'sheet': sheet, 'row': n, 'type': 'no school ID', 'name': name.strip(), 'district': dist,
                                   'detail': 'Listed without an ID (an extension site). Not imported; confirm whether it is a separate school.'})
                continue
            if not isinstance(name, str) or not name.strip():
                issues.append({'sheet': sheet, 'row': n, 'type': 'missing name', 'id': sid}); continue
            d = DISTRICT_ALIASES.get(str(dist or '').strip().lower())
            if d is None:
                issues.append({'sheet': sheet, 'row': n, 'type': 'unmapped district', 'id': sid, 'name': name, 'district': dist}); continue
            rows.append({'sheet': sheet, 'row': n, 'deped_id': int(sid), 'name': re.sub(r'\s+', ' ', name).strip(), 'district': d,
                         'raw_district': dist, 'level': level})
    return rows, issues

def analyse(rows, issues):
    byid = collections.defaultdict(list); byname = collections.defaultdict(list)
    for r in rows:
        byid[r['deped_id']].append(r); byname[(r['name'].lower(), r['district'], r['level'])].append(r)
    for k, v in byid.items():
        if len(v) > 1: issues.append({'type': 'duplicate ID', 'id': k, 'rows': [f"{x['sheet']}!{x['row']} {x['name']}" for x in v]})
    for k, v in byname.items():
        if len(v) > 1: issues.append({'type': 'duplicate name in district and level', 'name': k[0], 'rows': [f"{x['sheet']}!{x['row']} id {x['deped_id']}" for x in v]})
    for r in rows:
        if r['raw_district'] != r['district']:
            issues.append({'type': 'district name normalised', 'sheet': r['sheet'], 'row': r['row'], 'name': r['name'], 'from': r['raw_district'], 'to': r['district']})
    # level cue: names ending NHS are secondary, ES/IS/PS/CES are elementary: flag a sheet/level mismatch
    for r in rows:
        n = r['name'].upper()
        if r['level'] == 'elementary' and re.search(r'\bNHS\b|HIGH SCHOOL|ACADEMY', n):
            issues.append({'type': 'level cue disagrees with worksheet', 'name': r['name'], 'sheet': r['sheet'], 'row': r['row']})
        if r['level'] == 'secondary' and re.search(r'\b(ES|IS|PS|CES)\b|ELEMENTARY', n):
            issues.append({'type': 'level cue disagrees with worksheet', 'name': r['name'], 'sheet': r['sheet'], 'row': r['row']})
    return issues

def sql_lit(s): return "'" + s.replace("'", "''") + "'"

def build_sql(rows):
    vals = ",\n".join(f"  ({r['deped_id']}, {sql_lit(r['name'])}, {sql_lit(r['district'])}, {sql_lit(r['level'])})" for r in rows)
    return f"""-- Generated by tools/school_import.py from List-of-School.xlsx ({len(rows)} schools). Review, then run once in the SQL editor
-- AFTER migration 0013. Idempotent: schools already present (same DepEd school ID, or same name in the same district) are
-- matched and only get the missing DepEd ID / education level filled in; nothing is overwritten or deleted, and no
-- Special Programs / IPED assignment is created (the workbook does not say which schools take part). With migration 0014
-- applied, the schools also get the MAPEH tag.
begin;
create temp table _wb(deped_id integer, name text, district text, level text) on commit drop;
insert into _wb values
{vals};

-- 1. Existing schools matched by DepEd ID, then by name + district: fill the blanks only.
update public.schools s set deped_school_id = w.deped_id
  from _wb w join public.districts d on d.name = w.district
 where s.deped_school_id is null and s.district_id = d.id and lower(btrim(s.name)) = lower(w.name)
   and not exists (select 1 from public.schools z where z.deped_school_id = w.deped_id);
update public.schools s set education_level = w.level
  from _wb w where s.deped_school_id = w.deped_id and s.education_level is null;

-- 2. New schools: not present by DepEd ID and not present by name in that district.
insert into public.schools (name, district_id, active, deped_school_id, education_level)
select w.name, d.id, true, w.deped_id, w.level
  from _wb w join public.districts d on d.name = w.district
 where not exists (select 1 from public.schools s where s.deped_school_id = w.deped_id)
   and not exists (select 1 from public.schools s where s.district_id = d.id and lower(btrim(s.name)) = lower(w.name));

-- 2b. Every school teaches MAPEH: tag the workbook's schools with the MAPEH program (needs migration 0014). Nothing is
-- tagged Special Programs or IPED. Before 0014 this step only prints a notice.
do $$ begin
  insert into public.school_programs (school_id, program)
    select s.id, 'mapeh' from public.schools s where s.deped_school_id in (select deped_id from _wb) on conflict do nothing;
exception when check_violation then
  raise notice 'Run migration 0014 first, then run this script again to give the schools their MAPEH tag.';
end $$;

-- 3. Report (read-only): conflicts that were NOT changed.
select 'conflict: same DepEd ID, different district or name' as note, s.name as in_database, w.name as in_workbook, w.district as workbook_district
  from _wb w join public.schools s on s.deped_school_id = w.deped_id
  join public.districts d on d.id = s.district_id
 where d.name <> w.district or lower(btrim(s.name)) <> lower(w.name);
select 'review: school already in the database but not in the workbook (kept as is)' as note, s.name, d.name as district
  from public.schools s join public.districts d on d.id = s.district_id
 where s.deped_school_id is null or not exists (select 1 from _wb w where w.deped_id = s.deped_school_id)
 order by d.name, s.name;
select count(*) as schools_in_database_now from public.schools;
commit;
"""

if __name__ == '__main__':
    rows, issues = load(sys.argv[1]); issues = analyse(rows, issues)
    out = sys.argv[2]
    json.dump({'schools': rows, 'issues': issues}, open(f'{out}/schools_validated.json', 'w'), indent=1, ensure_ascii=False)
    open(f'{out}/school_import.sql', 'w').write(build_sql(rows))
    c = collections.Counter((r['level'], r['district']) for r in rows)
    print(len(rows), 'schools;', len(issues), 'issues'); print(collections.Counter(r['level'] for r in rows))
    for k in sorted(c): print(k, c[k])
    for i in issues: print(i)
